/** Isolated design identities; never entered into the actual business audit. Local Vite only. */
export async function seedLocalShareRecords(service,user,token){
  if(process.env.NODE_ENV==='production'||!service.demoShareCodes||!user.demoBusiness)return;
  const records=service.shareRecords,share=records.owned(user,token);
  service.publicOrder(token);
  const prefix=`${records.id(share)}:local-mock-v2:`;
  if(service.state.shareEvents.some(e=>e.id.startsWith(prefix)))return;
  // Replace only the explicit v1 synthetic fixture. Real access and audit events remain intact.
  const legacy=`${records.id(share)}:local-mock-v1:`;
  service.state.shareEvents=service.state.shareEvents.filter(e=>!(e.dataOrigin==='local-mock'&&e.id.startsWith(legacy)));
  service.state.shareDemoIdentities??={};
  const identities=[{id:prefix+'doctor',name:'张予安',role:'医生'},{id:prefix+'patient',name:'林若宁',role:'患者'}];
  identities.forEach(identity=>service.state.shareDemoIdentities[identity.id]={...identity,dataOrigin:'isolated-design-fixture'});
  // Fixed on first creation and persisted; no records are generated by Drawer reads.
  const base=+service.now();
  for(let i=0;i<16;i++){
    const success=i%4!==2,identity=success?identities[i%2]:null;
    const common={shareId:records.id(share),orderId:share.orderId,stageId:share.stageId,resultId:share.resultId,resultVersion:share.resultVersion,initiatorId:share.initiatorId||share.owner,dataOrigin:'local-mock',at:new Date(base-(16-i)*7*60000).toISOString()};
    service.state.shareEvents.push({...common,id:prefix+i+':open',type:'open'});
    const denied=!success&&i%8===6;
    service.state.shareEvents.push({...common,id:prefix+i+':result',type:success?'viewed':denied?'access-denied':'verification-failed',visitorId:identity?.id||null,visitorName:identity?.name||'未确认身份',visitorRole:identity?.role||'未确认',outcome:success?'查看成功':denied?'无访问权限':'验证失败'});
  }
  await service.persist(service.state);
}
